"""Extract the approved, generated art atlases without changing the paintings.

The original PNGs and exact generation prompts remain under midnight/sources.
Run from the project root. Pillow is also used by the existing art pipeline.
"""
import json
from pathlib import Path
from PIL import Image, PngImagePlugin

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'dist/assets/tavern-brawl/midnight'
SOURCES = BASE / 'sources'
GROUPS = {
    'crew-core': ['tavern-rat','mouse-guard','barroom-bruiser','badger-sentinel','fox-cutpurse','raven-cutpurse','owl-apprentice','hedgehog-watchman','stoat-gambler','hare-runner','toad-brewer','raccoon-scavenger','cinder-rat','wickrunner-bat','ironjaw-bouncer','lantern-moth'],
    'crew-midnight': ['bell-tower-marksman','mordren-ashen-host','sootpaw-lookout','gutterglass-duelist','vesper-blackpaw-king','ashveil-acolyte','nightglass-diviner','orun-eclipse-warden','gravewax-collector','debt-eater','mother-nox-bellkeeper','black-iron-buckler','shatter-the-seal','furnace-burst','the-bell-tolls','cut-the-purse'],
    'tricks': ['pocket-sand','last-call','loaded-dice','bar-fight','pilfer','second-wind','smoke-bomb','raven-bargain','rusty-dagger','oak-shield','lucky-coin','hearth-lantern','house-edge','moonlit-stitch','sealed-constellation','collect-the-debt'],
    'relics': ['funeral-velvet'],
}

def metadata(source, index=None):
    info = PngImagePlugin.PngInfo()
    prompt = (SOURCES / (source + '.prompt.txt')).read_text()
    info.add_text('generation-prompt', prompt)
    info.add_text('provenance', f'Built-in ImageGen; approved by user 2026-11-02. Source {source}.png; tile {index}. Unmodified rectangular atlas extraction.')
    return info

manifest = {}
(BASE / 'cards').mkdir(exist_ok=True)
(BASE / 'legends').mkdir(exist_ok=True)
for source, ids in GROUPS.items():
    atlas = Image.open(SOURCES / (source + '.png'))
    columns = rows = 2 if source == 'relics' else 4
    for index, card_id in enumerate(ids):
        x, y = index % columns, index // columns
        rect = (round(x * atlas.width / columns), round(y * atlas.height / rows), round((x + 1) * atlas.width / columns), round((y + 1) * atlas.height / rows))
        file = BASE / 'cards' / (card_id + '.png')
        atlas.crop(rect).save(file, pnginfo=metadata(source, index), optimize=True)
        manifest[card_id] = {'art': f'midnight/cards/{card_id}.png', 'source': source, 'tile': index, 'rect': rect}

legends = ['mordren-ashen-host','vesper-blackpaw-king','orun-eclipse-warden','mother-nox-bellkeeper']
atlas = Image.open(SOURCES / 'legends.png').convert('RGBA')
assert atlas.getextrema()[3][0] == 0, 'Legend sprites require native transparency'
for i, card_id in enumerate(legends):
    atlas.crop((round(i * atlas.width / 4),0,round((i+1)*atlas.width/4),atlas.height)).save(BASE/'legends'/(card_id+'.png'),pnginfo=metadata('legends',i),optimize=True)

for source in ['board','board-mobile']:
    im=Image.open(SOURCES/(source+'.png')).convert('RGB')
    im.save(BASE/(source+'.jpg'),quality=92,optimize=True)
    (BASE/(source+'.jpg.prompt.txt')).write_text((SOURCES/(source+'.prompt.txt')).read_text())

catalog=json.loads((ROOT/'dist/assets/tavern-brawl/cards.json').read_text())
assert set(manifest)=={c['id'] for c in catalog['cards']}, 'Every catalog card must have original midnight art'
(BASE/'manifest.json').write_text(json.dumps({'version':1,'approval':'User: Approve — use these assets and finish the build','cards':manifest,'legends':legends},indent=2)+'\n')
module='// Generated by scripts/tavern-brawl/prepare-midnight.py.\n'
module+='export const MIDNIGHT_ART=Object.freeze('+json.dumps({id:item['art'] for id,item in manifest.items()},indent=2)+');\n'
module+='export const LEGEND_ART=Object.freeze('+json.dumps({id:'midnight/legends/'+id+'.png' for id in legends},indent=2)+');\n'
module+="export const cardArtwork=card=>MIDNIGHT_ART[card.id]||card.art;\n"
(ROOT/'dist/brawl/midnight-art.js').write_text(module)
print(f'Prepared {len(manifest)} card illustrations, {len(legends)} native-alpha legend sprites, desktop and portrait board plates.')
