// Keep the original artwork in dist; publish only optimized, static web files.
import { readdir, readFile, writeFile, mkdir, rm, copyFile, stat } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const source = path.resolve('dist');
const output = path.resolve('web-dist');
const files = [];
async function walk(dir) {
  for (const entry of await readdir(dir, {withFileTypes:true})) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(file);
    else files.push(path.relative(source, file));
  }
}
await walk(source);
await rm(output, {recursive:true, force:true});
// App icons and social previews retain their conventional formats.
const keepOriginal = /(?:^|\/)(?:favicon-[^/]+|apple-touch-icon|icon-[^/]+)\.png$|(?:^|\/)social-share\.jpg$/;
const images = new Set(files.filter(file => /\.(png|jpg)$/.test(file) && !keepOriginal.test(file)));
const retained = files.filter(file => keepOriginal.test(file));
function rewrite(text) {
  // Include dynamically assembled names, e.g. heroes/${id}.png. Keeping the
  // original extension in the new name avoids collisions between PNG/JPEG pairs.
  let result = text.replace(/\.(png|jpg)\b(?!\.webp)/g, '.$1.webp');
  for (const file of retained) {
    const name = path.basename(file);
    result = result.replaceAll(`${name}.webp`, name);
  }
  return result;
}
let cursor = 0, before = 0, after = 0;
async function worker() {
  while (cursor < files.length) {
    const file = files[cursor++];
    const input = path.join(source, file);
    const target = path.join(output, images.has(file) ? `${file}.webp` : file);
    await mkdir(path.dirname(target), {recursive:true});
    before += (await stat(input)).size;
    if (images.has(file)) {
      // Preserve pixel dimensions and full alpha: sprite and border-image
      // coordinates must remain exactly aligned with the original artwork.
      await sharp(input).webp({quality:84, alphaQuality:100, effort:5}).toFile(target);
    } else if (/\.(html|css|js|json|webmanifest|svg)$/.test(file) && file !== 'loading-assets.js') {
      await writeFile(target, rewrite(await readFile(input, 'utf8')));
    } else await copyFile(input, target);
    after += (await stat(target)).size;
  }
}
await Promise.all(Array.from({length:4}, worker));
// Recompute progress weights from the files actually sent to visitors.
const {loadingAssets} = await import('../dist/loading-assets.js');
const entries = await Promise.all(loadingAssets.map(async asset => {
  const url = images.has(asset.url) ? `${asset.url}.webp` : asset.url;
  return {url, bytes:(await stat(path.join(output, url))).size};
}));
await writeFile(path.join(output, 'loading-assets.js'), `// Generated by npm run build.\nexport const loadingAssets = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`Static web build: ${(before/1048576).toFixed(1)} → ${(after/1048576).toFixed(1)} MB (${(100*(1-after/before)).toFixed(1)}% smaller).`);
console.log(`Startup preload: ${entries.length} files, ${(entries.reduce((sum,a)=>sum+a.bytes,0)/1048576).toFixed(2)} MB.`);
